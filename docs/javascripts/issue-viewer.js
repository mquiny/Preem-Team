/* ==========================================================================
   Preem Team — Issue Viewer search + label filtering
   Powers every [data-pt-issue-viewer] block — currently
   docs/troubleshooting/issue_viewer.md (open issues) and
   docs/troubleshooting/issue_archive.md (closed issues). Both tables are
   regenerated by scripts/sync-issues.js on every GitHub sync, so this
   reads whatever labels happen to be in a table at load time and builds
   filter chips from them — nothing here is hardcoded to a fixed label
   list, so it needs no maintenance as labels change.
   Runs on initial load and on every instant-navigation route change.
   ========================================================================== */
(function () {
  function labelsForRow(row, labelColIndex) {
    var cell = row.children[labelColIndex];
    if (!cell) return [];
    var codes = cell.querySelectorAll("code");
    return Array.prototype.map.call(codes, function (code) {
      return code.textContent.trim();
    });
  }

  function buildChip(text, value) {
    var btn = document.createElement("button");
    btn.type = "button";
    btn.className = "pt-issue-filter-chip";
    btn.textContent = text;
    btn.setAttribute("data-pt-filter-value", value);
    return btn;
  }

  function initIssueFilters(root) {
    var containers = (root || document).querySelectorAll("[data-pt-issue-viewer]");

    containers.forEach(function (container) {
      var filterBar = container.querySelector("[data-pt-issue-filters]");
      var searchInput = container.querySelector("[data-pt-issue-search]");
      var table = container.querySelector("table");
      if (!table) {
        return;
      }

      var rows = Array.prototype.slice.call(table.querySelectorAll("tbody tr"));
      if (!rows.length) {
        return;
      }

      var headerCells = Array.prototype.slice.call(table.querySelectorAll("thead th"));
      var issueColIndex = headerCells.findIndex(function (th) {
        return th.textContent.trim().toLowerCase() === "issue";
      });
      var labelColIndex = headerCells.findIndex(function (th) {
        return th.textContent.trim().toLowerCase() === "labels";
      });

      var activeLabel = "";

      function applyFilters() {
        var query = searchInput ? searchInput.value.trim().toLowerCase() : "";
        rows.forEach(function (row) {
          var labelMatch = true;
          if (activeLabel) {
            var rowLabels = (row.getAttribute("data-pt-labels") || "").split("|");
            labelMatch = rowLabels.indexOf(activeLabel) !== -1;
          }

          var textMatch = true;
          if (query) {
            var haystack = issueColIndex !== -1 && row.children[issueColIndex]
              ? row.children[issueColIndex].textContent
              : row.textContent;
            textMatch = haystack.toLowerCase().indexOf(query) !== -1;
          }

          row.hidden = !(labelMatch && textMatch);
        });
      }

      // Label chips — built from whatever labels are actually present in
      // this table right now. Skipped entirely if the Labels column is
      // missing, or if the table has no labelled rows to filter by.
      if (labelColIndex !== -1 && filterBar) {
        var seenLabels = {};
        rows.forEach(function (row) {
          var labels = labelsForRow(row, labelColIndex);
          row.setAttribute("data-pt-labels", labels.join("|"));
          labels.forEach(function (label) {
            seenLabels[label] = true;
          });
        });

        var labelNames = Object.keys(seenLabels).sort(function (a, b) {
          return a.localeCompare(b);
        });

        if (labelNames.length) {
          filterBar.innerHTML = "";
          filterBar.hidden = false;

          var allChip = buildChip("All", "");
          allChip.classList.add("is-active");
          filterBar.appendChild(allChip);

          labelNames.forEach(function (label) {
            filterBar.appendChild(buildChip(label, label));
          });

          filterBar.addEventListener("click", function (e) {
            var chip = e.target.closest ? e.target.closest("[data-pt-filter-value]") : null;
            if (!chip || !filterBar.contains(chip)) {
              return;
            }

            Array.prototype.forEach.call(filterBar.querySelectorAll(".pt-issue-filter-chip"), function (btn) {
              btn.classList.toggle("is-active", btn === chip);
            });

            activeLabel = chip.getAttribute("data-pt-filter-value");
            applyFilters();
          });
        }
      }

      // Title search — works regardless of whether label chips exist.
      if (searchInput) {
        searchInput.addEventListener("input", applyFilters);
      }
    });
  }

  if (typeof document$ !== "undefined") {
    // Material's instant-navigation observable — fires on first load too.
    document$.subscribe(function () {
      initIssueFilters(document);
    });
  } else {
    document.addEventListener("DOMContentLoaded", function () {
      initIssueFilters(document);
    });
  }
})();
