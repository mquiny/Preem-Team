/* ==========================================================================
   Preem Team — StreetCred leaderboard staff filter
   Powers the [data-pt-streetcred] block on docs/team/streetcred.md.
   The table itself is regenerated by scripts/apply-streetcred.js on every
   daily sync; this just toggles visibility of rows tagged data-staff="true"
   client-side. Default is "All Members" — staff are shown unless the
   viewer explicitly hides them, since staff would otherwise always sit
   at the top and crowd out everyone else's ranking.
   Runs on initial load and on every instant-navigation route change.
   ========================================================================== */
(function () {
  function initStreetCredFilter(root) {
    var containers = (root || document).querySelectorAll("[data-pt-streetcred]");

    containers.forEach(function (container) {
      var toolbar = container.querySelector("[data-pt-streetcred-toolbar]");
      var rows = container.querySelectorAll(".pt-streetcred-table tbody tr");
      if (!toolbar || !rows.length) {
        return;
      }

      toolbar.addEventListener("click", function (e) {
        var chip = e.target.closest ? e.target.closest("[data-pt-staff-filter]") : null;
        if (!chip || !toolbar.contains(chip)) {
          return;
        }

        Array.prototype.forEach.call(toolbar.querySelectorAll(".pt-streetcred-filter-chip"), function (btn) {
          btn.classList.toggle("is-active", btn === chip);
        });

        var hideStaff = chip.getAttribute("data-pt-staff-filter") === "members";
        rows.forEach(function (row) {
          row.hidden = hideStaff && row.getAttribute("data-staff") === "true";
        });
      });
    });
  }

  if (typeof document$ !== "undefined") {
    document$.subscribe(function () {
      initStreetCredFilter(document);
    });
  } else {
    document.addEventListener("DOMContentLoaded", function () {
      initStreetCredFilter(document);
    });
  }
})();
